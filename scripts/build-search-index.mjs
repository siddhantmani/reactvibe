import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const groups = [
    { dir: "lib/blocks", base: "/docs/blocks", label: "Blocks" },
    { dir: "lib/dashboardUi", base: "/docs/dashboard-ui", label: "Dashboard UI" },
];
const str = String.raw`(?:"((?:[^"\\]|\\.)*)"|'((?:[^'\\]|\\.)*)'|\x60((?:[^\x60\\]|\\.)*)\x60)`;
const field = (b, k) => { const m = b.match(new RegExp(`\\b${k}\\s*:\\s*${str}`)); return m ? (m[1] ?? m[2] ?? m[3]) : undefined; };
const tagsOf = (b) => { const m = b.match(/\btags\s*:\s*\[([\s\S]*?)\]/); return m ? [...m[1].matchAll(new RegExp(str, "g"))].map(x => x[1] ?? x[2] ?? x[3]) : []; };

const items = [];
for (const g of groups) {
    for (const category of fs.readdirSync(path.join(root, g.dir)).sort()) {
        const file = path.join(root, g.dir, category, "index.ts");
        if (!fs.existsSync(file)) continue;
        const src = fs.readFileSync(file, "utf8");
        const start = src.search(/export\s+const\s+\w+\s*(?::[^=]+)?=\s*\[/);
        for (const body of src.slice(start).split(/(?=\bname\s*:)/).slice(1)) {
            const name = field(body, "name"), slug = field(body, "slug");
            if (!name || !slug) continue;
            items.push({
                name, path: `${g.base}/${category}/${slug}`, section: `${g.label} / ${category}`,
                keywords: [...tagsOf(body), field(body, "description") ?? ""]
            });
        }
    }
}
fs.writeFileSync(path.join(root, "lib/search-index.generated.ts"),
    `// AUTO-GENERATED by scripts/build-search-index.mjs
import type { SearchItem } from "./searchable-components";
export const generatedSearchItems: SearchItem[] = ${JSON.stringify(items, null, 4)};
`);
console.log(`search index: ${items.length} items`);